"""Report generation: Markdown + JSON summaries of an evaluation and a
conveyor run. The Markdown report is human-readable and self-contained;
the JSON file carries the same numbers for downstream tooling.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import config


def _confusion_table(matrix: dict[str, dict[str, int]],
                     labels: tuple[str, ...]) -> str:
    header = "| true \\ pred | " + " | ".join(labels) + " |"
    divider = "|" + "---|" * (len(labels) + 1)
    rows = [header, divider]
    for true_label in labels:
        cells = " | ".join(str(matrix[true_label][p]) for p in labels)
        rows.append(f"| **{true_label}** | {cells} |")
    return "\n".join(rows)


def build_report(evaluation: dict, conveyor: dict, dataset_name: str,
                 output_dir: Path) -> tuple[Path, Path]:
    """Write ``report.md`` and ``report.json`` into ``output_dir``.

    Returns the two paths written.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    md_path = output_dir / "report.md"
    json_path = output_dir / "report.json"

    det = evaluation["detection"]
    lines = [
        "# Vision Sorter — Run Report",
        "",
        f"Dataset: `{dataset_name}` — {evaluation['frames']} frames, "
        f"{evaluation['total']} matched objects, "
        f"mean frame time {evaluation['mean_frame_ms']} ms.",
        "",
        "## Classification",
        "",
        f"- **Accuracy: {evaluation['accuracy']:.4f}** "
        f"({evaluation['correct']}/{evaluation['total']} correct)",
        f"- Macro precision: {evaluation['macro_precision']:.4f}",
        f"- Macro recall: {evaluation['macro_recall']:.4f}",
        f"- Macro F1: {evaluation['macro_f1']:.4f}",
        "",
        "### Confusion matrix",
        "",
        _confusion_table(evaluation["confusion_matrix"], config.CLASSES),
        "",
        "### Per-class metrics",
        "",
        "| class | precision | recall | F1 | support |",
        "|---|---|---|---|---|",
    ]
    for label in config.CLASSES:
        m = evaluation["per_class"][label]
        lines.append(f"| {label} | {m['precision']:.3f} | {m['recall']:.3f} "
                     f"| {m['f1']:.3f} | {m['support']} |")
    lines += [
        "",
        "## Detection",
        "",
        f"- Objects in ground truth: {det['truth']}",
        f"- Objects detected: {det['detected']}",
        f"- Matched: {det['matched']}",
        f"- Detection precision: {det['precision']:.4f}",
        f"- Detection recall: {det['recall']:.4f}",
        f"- Detection F1: {det['f1']:.4f}",
        "",
        "## Conveyor run",
        "",
        f"- Items sorted: {conveyor['total_items']}",
        f"- Simulated duration: {conveyor['duration_s']} s "
        f"({conveyor['items_per_min']} items/min)",
        f"- Lanes: accept {conveyor['lane_counts'].get('accept', 0)}, "
        f"divert {conveyor['lane_counts'].get('divert', 0)}, "
        f"reject {conveyor['lane_counts'].get('reject', 0)}",
        f"- False accepts (defect shipped): {conveyor['false_accepts']}",
        f"- False rejects (good part scrapped): {conveyor['false_rejects']}",
        f"- Unknown: {conveyor['unknown']}",
        f"- Sort error rate: {conveyor['error_rate']:.4f}",
        f"- Sort accuracy: {conveyor['accuracy']:.4f}",
        f"- Mean inspection time: {conveyor['mean_inspect_ms']} ms/item",
        "",
        "_Generated by vision-sorter-sim. All numbers come from real runs "
        "on synthetic data with known ground truth._",
        "",
    ]
    md_path.write_text("\n".join(lines), encoding="utf-8")
    payload = {"dataset": dataset_name, "evaluation": evaluation,
               "conveyor": conveyor}
    json_path.write_text(json.dumps(payload, indent=2, default=str),
                         encoding="utf-8")
    return md_path, json_path
