"""Static HTML dashboard: one self-contained page (Chart.js via CDN)
showing the evaluation confusion matrix, per-class precision/recall/F1
bars, lane distribution and the conveyor throughput series. No server
needed — open the file in a browser.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import config
from .conveyor import throughput_series

CHARTJS_CDN = "https://cdn.jsdelivr.net/npm/chart.js@4.4.1/dist/chart.umd.min.js"

DASHBOARD_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Vision Sorter — Dashboard</title>
<script src="{cdn}"></script>
<style>
  body {{ font-family: system-ui, sans-serif; margin: 2rem auto; max-width: 960px;
         padding: 0 1rem; color: #1d2a32; background: #f7f8f8; }}
  h1 {{ font-size: 1.6rem; }} h2 {{ font-size: 1.2rem; margin-top: 2rem; }}
  .cards {{ display: grid; grid-template-columns: repeat(4, 1fr); gap: 0.8rem; }}
  .card {{ background: #fff; border-radius: 10px; padding: 1rem; box-shadow: 0 1px 4px #0002; }}
  .card b {{ font-size: 1.5rem; display: block; }}
  table {{ border-collapse: collapse; background: #fff; }}
  td, th {{ border: 1px solid #ccd; padding: 0.35rem 0.6rem; text-align: center; }}
  th {{ background: #1d2a32; color: #fff; }}
  canvas {{ background: #fff; border-radius: 10px; padding: 0.5rem; max-width: 100%; }}
  .note {{ color: #555; font-size: 0.9rem; }}
</style>
</head>
<body>
<h1>Vision Sorter — Conveyor Dashboard</h1>
<p class="note">Dataset: {dataset} &middot; {frames} frames &middot; {total} matched objects
&middot; mean frame time {frame_ms} ms</p>

<div class="cards">
  <div class="card"><b>{accuracy:.2%}</b>classification accuracy</div>
  <div class="card"><b>{macro_f1:.3f}</b>macro F1</div>
  <div class="card"><b>{items_per_min:.0f}/min</b>throughput</div>
  <div class="card"><b>{error_rate:.2%}</b>sort error rate</div>
</div>

<h2>Per-class precision / recall / F1</h2>
<canvas id="prf" height="120"></canvas>

<h2>Confusion matrix (rows = true, columns = predicted)</h2>
{cm_table}

<h2>Sort lanes</h2>
<canvas id="lanes" height="120"></canvas>

<h2>Throughput over time</h2>
<canvas id="throughput" height="120"></canvas>

<p class="note">False accepts (defect shipped): {false_accepts} &middot;
False rejects (good part scrapped): {false_rejects} &middot; Unknown: {unknown} &middot;
Detection precision {det_p:.3f} / recall {det_r:.3f} &middot;
Generated by vision-sorter-sim from real runs on synthetic data.</p>

<script>
const labels = {labels_json};
const perClass = {per_class_json};
new Chart(document.getElementById('prf'), {{ type: 'bar',
  data: {{ labels, datasets: [
    {{ label: 'precision', data: perClass.map(c => c.precision), backgroundColor: '#20a145' }},
    {{ label: 'recall', data: perClass.map(c => c.recall), backgroundColor: '#1d2a32' }},
    {{ label: 'F1', data: perClass.map(c => c.f1), backgroundColor: '#e8a838' }} ] }},
  options: {{ scales: {{ y: {{ min: 0, max: 1 }} }} }} }});
new Chart(document.getElementById('lanes'), {{ type: 'doughnut',
  data: {{ labels: ['accept', 'divert', 'reject'],
    datasets: [{{ data: {lanes_json},
      backgroundColor: ['#20a145', '#2f7fc1', '#d64545'] }}] }} }});
new Chart(document.getElementById('throughput'), {{ type: 'line',
  data: {{ labels: {tp_labels_json},
    datasets: [{{ label: 'items/min', data: {tp_values_json},
      borderColor: '#1d2a32', backgroundColor: '#20a14533', fill: true }}] }},
  options: {{ scales: {{ y: {{ beginAtZero: true }} }} }} }});
</script>
</body>
</html>
"""


def _confusion_html(matrix: dict[str, dict[str, int]],
                    labels: tuple[str, ...]) -> str:
    rows = ["<table><tr><th>true \\ pred</th>"
            + "".join(f"<th>{lab}</th>" for lab in labels) + "</tr>"]
    for true_label in labels:
        cells = "".join(f"<td>{matrix[true_label][p]}</td>" for p in labels)
        rows.append(f"<tr><th>{true_label}</th>{cells}</tr>")
    rows.append("</table>")
    return "\n".join(rows)


def build_dashboard(evaluation: dict, conveyor_run, dataset_name: str,
                    output_path: Path) -> Path:
    """Render the dashboard HTML for an evaluation + conveyor run."""
    per_class = [{"label": lab, **evaluation["per_class"][lab]}
                 for lab in config.CLASSES]
    series = throughput_series(conveyor_run)
    lanes = [conveyor_run.lane_counts.get(k, 0)
             for k in ("accept", "divert", "reject")]
    html = DASHBOARD_TEMPLATE.format(
        cdn=CHARTJS_CDN,
        dataset=dataset_name,
        frames=evaluation["frames"],
        total=evaluation["total"],
        frame_ms=evaluation["mean_frame_ms"],
        accuracy=evaluation["accuracy"],
        macro_f1=evaluation["macro_f1"],
        items_per_min=conveyor_run.items_per_min,
        error_rate=conveyor_run.error_rate,
        false_accepts=conveyor_run.false_accepts,
        false_rejects=conveyor_run.false_rejects,
        unknown=conveyor_run.unknown,
        det_p=evaluation["detection"]["precision"],
        det_r=evaluation["detection"]["recall"],
        labels_json=json.dumps(list(config.CLASSES)),
        per_class_json=json.dumps(per_class),
        cm_table=_confusion_html(evaluation["confusion_matrix"], config.CLASSES),
        lanes_json=json.dumps(lanes),
        tp_labels_json=json.dumps([f"{s['t_min']:.0f} min" for s in series]),
        tp_values_json=json.dumps([s["items_per_min"] for s in series]),
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(html, encoding="utf-8")
    return output_path
